inline const std::map<std::string, int>& decoder_host_service_ids() {
  static const std::map<std::string, int> services = [] {
    std::map<std::string, int> result;
    for (const auto& entry : kHostServiceRegistry)
      if (entry.decoder_eligible) result.emplace(entry.symbol, entry.id);
    return result;
  }();
  return services;
}

inline const std::unordered_map<std::string, int>& runner_host_service_ids() {
  static const std::unordered_map<std::string, int> services = [] {
    std::unordered_map<std::string, int> result;
    for (const auto& entry : kHostServiceRegistry)
      if (entry.runner_eligible) result.emplace(entry.symbol, entry.id);
    return result;
  }();
  return services;
}

